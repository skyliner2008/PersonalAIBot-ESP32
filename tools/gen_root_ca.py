#!/usr/bin/env python3
"""
Extract the root CAs used by *.googleapis.com from a Mozilla CA bundle
(certifi's cacert.pem) into src/ai/GoogleRootCA.h.

    python tools/gen_root_ca.py            # uses certifi.where()
    python tools/gen_root_ca.py --bundle /etc/ssl/certs/ca-certificates.crt

Google serves RSA chains ending at GTS Root R1 and ECDSA chains ending at
GTS Root R4 (cross-signed by GlobalSign ECC Root CA - R4). These are the
roots Mozilla still trusts (GTS R2 / GlobalSign R1 were removed from the
bundle); GTS roots expire 2036, GlobalSign ECC R4 in 2038.
"""

import argparse
import re

ROOTS = ["GTS Root R1", "GTS Root R3", "GTS Root R4", "GlobalSign ECC Root CA - R4"]
# Data tools (src/agent/WebTools.cpp): Open-Meteo (Let's Encrypt), oil-price.bangchak.co.th (DigiCert G2),
# scanner.tradingview.com (Amazon); news.google.com chains to GTS Root R1 (above).
WEB_ROOTS = ["ISRG Root X1", "DigiCert Global Root G2", "Amazon Root CA 1"]
# Firmware updates (src/system/OtaUpdater.cpp): api.github.com / github.com chain to USERTrust ECC
# (Sectigo E46 cross-signed), RSA clients to USERTrust RSA / Sectigo R46; the release download redirect
# (release-assets.githubusercontent.com) chains to ISRG Root X1 (X2 for ECDSA).
OTA_ROOTS = ["USERTrust ECC Certification Authority", "USERTrust RSA Certification Authority",
             "Sectigo Public Server Authentication Root E46", "Sectigo Public Server Authentication Root R46",
             "ISRG Root X1", "ISRG Root X2"]


def load_bundle(path):
    text = open(path, encoding="utf-8").read()
    certs = {}
    for m in re.finditer(r"# Label: \"([^\"]+)\"\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----)",
                         text, re.S):
        certs[m.group(1)] = m.group(2).strip()
    return certs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle")
    ap.add_argument("--out", default="src/ai/GoogleRootCA.h")
    args = ap.parse_args()
    bundle = args.bundle
    if not bundle:
        import certifi
        bundle = certifi.where()

    certs = load_bundle(bundle)
    missing = [r for r in ROOTS + WEB_ROOTS + OTA_ROOTS if r not in certs]
    if missing:
        raise SystemExit(f"missing in bundle: {missing}")

    def emit(f, var, names):
        f.write(f"static const char {var}[] =\n")
        for name in names:
            f.write(f"    // {name}\n")
            for line in certs[name].splitlines():
                f.write(f'    "{line}\\n"\n')
        f.write("    ;\n")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/**\n * @file GoogleRootCA.h\n * @brief Root CAs for TLS verification (Gemini API + data tools)\n")
        f.write(" * Generated by tools/gen_root_ca.py from the Mozilla CA bundle - do not edit.\n")
        f.write(" * GOOGLE_ROOT_CA_PEM: " + ", ".join(ROOTS) + "\n")
        f.write(" * WEB_ROOT_CA_PEM:    the above + " + ", ".join(WEB_ROOTS) + "\n")
        f.write(" * OTA_ROOT_CA_PEM:    " + ", ".join(OTA_ROOTS) + "\n */\n\n#pragma once\n\n")
        emit(f, "GOOGLE_ROOT_CA_PEM", ROOTS)
        f.write("\n")
        emit(f, "WEB_ROOT_CA_PEM", ROOTS + WEB_ROOTS)
        f.write("\n")
        emit(f, "OTA_ROOT_CA_PEM", OTA_ROOTS)
    print(f"wrote {args.out} ({len(ROOTS)} + {len(WEB_ROOTS)} + {len(OTA_ROOTS)} certificates)")


if __name__ == "__main__":
    main()
