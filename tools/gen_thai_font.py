#!/usr/bin/env python3
"""
Generate a LovyanGFX/TFT_eSPI compatible VLW font (Thai + ASCII) as a C array.

    python tools/gen_thai_font.py --size 26 --name ThaiFont26 \
        --out src/display/fonts --preview preview.png

(--ttf defaults to TH Sarabun New in the per-user or system Windows font folder)

Default font: TH Sarabun New (SIPA, free Thai national font).
Requires Pillow. Glyphs are rendered with the BASIC layout engine so that
Thai combining marks keep their own (zero-advance, negative-offset) metrics,
which LovyanGFX then overlays on the previous character.

VLW layout (big-endian int32):
  header : glyphCount, version(11), size, 0, ascent, descent
  glyphs : unicode, height, width, xAdvance, dY(top above baseline), dX(left offset), 0
  bitmaps: width*height bytes of 8-bit alpha per glyph, same order
"""

import argparse
import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x0E01, 0x0E3A),  # Thai consonants, vowels, marks
    (0x0E3F, 0x0E5B),  # Baht, leading vowels, tone marks, digits
]
EXTRA = [0x00B0, 0x00D7, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026]


def code_points():
    cps = []
    for a, b in RANGES:
        cps.extend(range(a, b + 1))
    cps.extend(EXTRA)
    return sorted(set(cps))


def glyph_missing(font, ch, notdef_mask):
    if ch == " ":
        return False
    mask = font.getmask(ch)
    return mask.size == notdef_mask.size and bytes(mask) == bytes(notdef_mask)


def build(ttf, size):
    font = ImageFont.truetype(ttf, size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    notdef = font.getmask("\uffff")

    glyphs = []
    for cp in code_points():
        ch = chr(cp)
        if glyph_missing(font, ch, notdef):
            continue
        advance = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if cp == 0x20 or w == 0 or h == 0:
            glyphs.append((cp, 0, 0, advance, 0, 0, b""))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        if not (-128 <= x0 <= 127):
            print(f"warning: U+{cp:04X} x offset {x0} out of range", file=sys.stderr)
            continue
        glyphs.append((cp, h, w, advance, -y0, x0, img.tobytes()))

    # LovyanGFX line height = max(header ascent, glyph tops) + max(header descent,
    # glyph bottoms). The TTF metrics of Sarabun reserve far more space than the
    # glyphs use, so store the real glyph extents to keep lines compact.
    ascent = max(g[4] for g in glyphs if g[1])
    descent = max(g[1] - g[4] for g in glyphs if g[1])
    return glyphs, ascent, descent


def to_vlw(glyphs, size, ascent, descent):
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for *_, bmp in glyphs:
        out += bmp
    return bytes(out)


def write_c(vlw, name, out_dir, ttf, size, count):
    os.makedirs(out_dir, exist_ok=True)
    header = os.path.join(out_dir, f"{name}.h")
    source = os.path.join(out_dir, f"{name}.cpp")
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            f"/**\n * @file {name}.h\n * @brief VLW font ({count} glyphs, {size}px) generated by tools/gen_thai_font.py\n"
            f" * Source font: {os.path.basename(ttf)}\n */\n\n#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
            f"extern const uint8_t {name}[];\nextern const size_t {name}_size;\n"
        )
    with open(source, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"// Generated by tools/gen_thai_font.py - do not edit\n#include \"{name}.h\"\n\n")
        f.write(f"const uint8_t {name}[] = {{\n")
        for i in range(0, len(vlw), 20):
            f.write("    " + ",".join(f"0x{b:02X}" for b in vlw[i:i + 20]) + ",\n")
        f.write("};\n")
        f.write(f"const size_t {name}_size = sizeof({name});\n")
    return header, source


def render_preview(glyphs, path, lines, scale=2, width=240):
    """Draw text the way LovyanGFX does (cursor += xAdvance; glyph at x+dX, top = baseline-dY)."""
    table = {g[0]: g for g in glyphs}
    max_asc = max((g[4] for g in glyphs if g[1]), default=0)
    max_desc = max((g[1] - g[4] for g in glyphs if g[1]), default=0)
    line_h = max_asc + max_desc
    img = Image.new("L", (width, line_h * len(lines) + 8), 20)
    for row, text in enumerate(lines):
        x = 4
        baseline = 4 + row * line_h + max_asc
        for ch in text:
            g = table.get(ord(ch))
            if not g:
                x += 6
                continue
            cp, h, w, adv, dy, dx, bmp = g
            if h and w:
                glyph = Image.frombytes("L", (w, h), bmp)
                img.paste(255, (x + dx, baseline - dy), glyph)
            x += adv
    img = img.resize((img.width * scale, img.height * scale), Image.NEAREST)
    img.save(path)
    return line_h


def default_ttf():
    candidates = [
        os.path.expandvars(r"%LOCALAPPDATA%\Microsoft\Windows\Fonts\THSarabunNew.ttf"),  # per-user install
        r"C:\Windows\Fonts\THSarabunNew.ttf",
        "/usr/share/fonts/truetype/tlwg/Sarabun.ttf",
    ]
    for c in candidates:
        if os.path.exists(c):
            return c
    return candidates[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", default=default_ttf())
    ap.add_argument("--size", type=int, default=26)
    ap.add_argument("--name", default="ThaiFont26")
    ap.add_argument("--out", default="src/display/fonts")
    ap.add_argument("--preview")
    args = ap.parse_args()

    glyphs, ascent, descent = build(args.ttf, args.size)
    vlw = to_vlw(glyphs, args.size, ascent, descent)
    header, source = write_c(vlw, args.name, args.out, args.ttf, args.size, len(glyphs))
    print(f"{len(glyphs)} glyphs, {len(vlw)} bytes -> {header}, {source}")
    if args.preview:
        lh = render_preview(glyphs, args.preview, [
            "สวัสดีครับ ผมชื่อไข่มุก",
            "ผู้ใช้ชอบกาแฟดำ น้ำตาลไม่ใส่",
            "กำลังฟัง... แตะเพื่อหยุด",
            "Ready 12:30 ฿99 ๑๒๓",
        ])
        print(f"line height {lh}px, preview -> {args.preview}")


if __name__ == "__main__":
    main()
